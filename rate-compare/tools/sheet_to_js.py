#!/usr/bin/env python3
"""Convert a CSV export of the "Rates" sheet into data/rates.js.

Usage:
    python3 tools/sheet_to_js.py Rates.csv [--retrieved 2026-11-25]

The CSV must have the sheet's header row:
bank_name, currency, term_months, rate_pct, amount_min, amount_max, amount_tier,
product, category, interest_payment, valid_from, valid_until, notes,
source_type, source_date, source_url, bank_id, retrieved
"""
import argparse, csv, json, os, sys

KEEP = ["bank_id", "bank_name", "currency", "term_months", "rate_pct", "amount_min",
        "amount_max", "amount_tier", "product", "category", "interest_payment",
        "valid_from", "valid_until", "notes", "source_type", "source_date", "source_url"]
NUMERIC = {"term_months", "rate_pct", "amount_min", "amount_max"}


def num(v):
    v = (v or "").strip().replace(",", "").replace("%", "")
    if not v:
        return None
    f = float(v)
    return int(f) if f.is_integer() else f


def convert(rows, retrieved):
    out = []
    for r in rows:
        rec = {}
        for k in KEEP:
            v = r.get(k)
            if k in NUMERIC:
                rec[k] = num(v)
            else:
                v = (v or "").strip()
                rec[k] = v or None
        out.append(rec)
    if not retrieved:
        retrieved = max((r.get("retrieved") or "" for r in rows), default="") or None
    return {"retrieved": retrieved, "withholdingTaxPct": 15, "insuranceLimitALL": 2500000, "rows": out}


def write_js(data, path):
    body = ",\n    ".join(json.dumps(r, ensure_ascii=False) for r in data["rows"])
    meta = {k: v for k, v in data.items() if k != "rows"}
    head = json.dumps(meta, ensure_ascii=False, indent=2)[:-2]
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/sheet_to_js.py from the 'Rates' sheet. Edit the sheet, export CSV, re-run. */\n")
        f.write("window.RATES_DATA = " + head + ",\n  \"rows\": [\n    " + body + "\n  ]\n};\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--retrieved")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "data", "rates.js"))
    a = ap.parse_args()
    with open(a.csv, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    if not rows or "bank_id" not in rows[0]:
        sys.exit("CSV is missing the sheet's header row (bank_id, currency, term_months, ...)")
    data = convert(rows, a.retrieved)
    write_js(data, a.out)
    print(f"Wrote {len(data['rows'])} rows to {os.path.normpath(a.out)}")
